"""Integration tests for voicelink/stream_cache.py against real components:
real audio generated by ffmpeg, the real StreamCache HTTP server (what
Lavalink plays from) and the real ffmpeg loudness measurement. No internet
needed - only ffmpeg (present in the bot image).

Guards against: the measurement silently breaking when the ffmpeg filter or
its output format changes (Patch 33 switched loudnorm -> ebur128), the
server not honouring the HTTP Range requests Lavalink seeks with (Patch 25
resume-at-position relies on them), and the low-priority wrappers not
existing in the image (Patch 33).
"""
from __future__ import annotations

import math
import shutil
import socket
import subprocess

import aiohttp
import pytest

from voicelink import stream_cache
from voicelink.stream_cache import StreamCache

pytestmark = [
    pytest.mark.integration,
    pytest.mark.skipif(not shutil.which("ffmpeg"), reason="ffmpeg not installed"),
]


def _tone(path, amplitude: float, seconds: int = 6) -> None:
    """Writes a 440Hz sine at `amplitude` (1.0 = full scale) as Opus/WebM -
    the same container/codec as the itag-251 files yt-dlp caches."""
    subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
         "-f", "lavfi", "-i", f"aevalsrc={amplitude}*sin(2*PI*440*t):d={seconds}:s=48000",
         "-c:a", "libopus", "-b:a", "128k", "-f", "webm", str(path)],
        check=True,
    )


def _db(gain: float) -> float:
    return 20 * math.log10(gain)


def _free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


@pytest.fixture
def cache_dir(tmp_path, monkeypatch):
    monkeypatch.setattr(stream_cache, "CACHE_DIR", tmp_path)
    return tmp_path


async def test_loud_tracks_are_turned_down_by_the_capped_amount(cache_dir):
    loud = cache_dir / "loud.audio"
    _tone(loud, 0.9)  # about -4 LUFS, far above the -14 target

    gain = await StreamCache._measure_gain(loud)

    assert gain is not None
    assert _db(gain) == pytest.approx(-8.0, abs=0.1)  # wants ~-10dB, clamped to the -8dB limit


async def test_a_moderately_quiet_track_is_boosted_toward_the_target(cache_dir):
    mid = cache_dir / "mid.audio"
    _tone(mid, 0.2)  # about -17 LUFS, peak about -14 dBFS: room to boost

    gain = await StreamCache._measure_gain(mid)

    assert gain is not None
    assert 1.5 < _db(gain) < 4.5


async def test_measured_gains_follow_loudness_order(cache_dir):
    gains = {}
    for name, amp in (("quiet", 0.03), ("mid", 0.2), ("loud", 0.9)):
        _tone(cache_dir / f"{name}.audio", amp)
        gains[name] = await StreamCache._measure_gain(cache_dir / f"{name}.audio", low_priority=True)

    assert gains["quiet"] > gains["mid"] > gains["loud"]
    assert _db(gains["quiet"]) == pytest.approx(8.0, abs=0.1)  # clamped to the +8dB limit


async def test_a_file_ffmpeg_cannot_read_measures_as_none(cache_dir):
    junk = cache_dir / "junk.audio"
    junk.write_bytes(b"this is not audio")

    assert await StreamCache._measure_gain(junk) is None


def test_the_low_priority_wrappers_exist_in_the_image():
    prefix = stream_cache._low_priority_prefix()

    assert prefix[:3] == ["nice", "-n", "15"]
    assert "ionice" in prefix
    subprocess.run([*prefix, "true"], check=True)  # actually runnable here, not just on PATH


async def test_the_server_serves_cached_audio_with_range_requests(cache_dir, monkeypatch):
    audio = cache_dir / "vidR.audio"
    _tone(audio, 0.5)
    (cache_dir / "vidR.meta.json").write_text('{"title": "Tone", "gain": 0.5, "gain_version": 2}')
    data = audio.read_bytes()
    port = _free_port()
    monkeypatch.setattr(stream_cache, "LISTEN_PORT", port)
    cache = StreamCache()
    await cache.start()
    try:
        base = f"http://127.0.0.1:{port}/stream"
        async with aiohttp.ClientSession() as http:
            async with http.get(f"{base}/vidR") as r:
                assert r.status == 200
                assert await r.read() == data
            async with http.get(f"{base}/vidR", headers={"Range": "bytes=100-199"}) as r:
                assert r.status == 206
                assert r.headers["Content-Range"] == f"bytes 100-199/{len(data)}"
                assert await r.read() == data[100:200]
            async with http.head(f"{base}/vidR") as r:
                assert r.status == 200
                assert int(r.headers["Content-Length"]) == len(data)
            async with http.get(f"{base}/notCached") as r:
                assert r.status == 404
        assert cache.gain("vidR") == pytest.approx(0.5)  # recovered from the sidecar on startup
    finally:
        await cache.stop()
